"""Saved designs: up to 8 messages of pixel frames + display settings, stored as JSON.

File format (``designs/<name>.json``)::

    {
      "version": 1,
      "name": "heart",
      "brightness": 100,
      "messages": [
        {"mode": "animation", "speed": 4, "blink": false, "marquee": false,
         "frames": [["....##..", "...", ...11 rows...], ...]}
      ]
    }

Each frame is 11 strings of ``.`` (off) / ``#`` (on), all the same width.
In animation mode every frame is a 44-px screen; in other modes the frames are
joined left-to-right into one bitmap (handy for long scrolling banners).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from PIL import Image

from .protocol import ANIM_OFFSET, HEIGHT, MAX_MESSAGES, Message, Mode, build_payload
from .render import animation_strip, blank

FORMAT_VERSION = 1
Rows = list[str]
_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 _.-]{0,63}$")


def image_to_rows(img: Image.Image) -> Rows:
    """1-bit image -> list of ``.#`` strings."""
    img = img.convert("1")
    px = img.load()
    return ["".join("#" if px[x, y] else "." for x in range(img.width)) for y in range(img.height)]


def rows_to_image(rows: Rows) -> Image.Image:
    """List of ``.#`` strings -> 1-bit image."""
    img = blank(len(rows[0]))
    px = img.load()
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "#":
                px[x, y] = 1
    return img


def _check_frame(rows: Rows) -> None:
    if len(rows) != HEIGHT:
        raise ValueError(f"frame must have {HEIGHT} rows, got {len(rows)}")
    widths = {len(r) for r in rows}
    if len(widths) != 1 or 0 in widths:
        raise ValueError("frame rows must be non-empty and equal width")
    if any(set(r) - {".", "#"} for r in rows):
        raise ValueError("frame rows may only contain '.' and '#'")


@dataclass
class DesignMessage:
    """One message slot of a design."""
    frames: list[Rows]
    mode: Mode = Mode.LEFT
    speed: int = 4
    blink: bool = False
    marquee: bool = False

    def bitmap(self, frame_offset: int = ANIM_OFFSET) -> Image.Image:
        """The bitmap uploaded for this message."""
        images = [rows_to_image(f) for f in self.frames]
        if self.mode == Mode.ANIMATION:
            return animation_strip(images, frame_offset)
        out = blank(sum(i.width for i in images))
        x = 0
        for i in images:
            out.paste(i, (x, 0))
            x += i.width
        return out

    def to_message(self, frame_offset: int = ANIM_OFFSET) -> Message:
        return Message(self.bitmap(frame_offset), self.mode, self.speed, self.blink, self.marquee)

    def to_json(self) -> dict:
        return {"mode": self.mode.name.lower(), "speed": self.speed, "blink": self.blink,
                "marquee": self.marquee, "frames": self.frames}

    @classmethod
    def from_json(cls, d: dict) -> "DesignMessage":
        frames = d["frames"]
        if not frames:
            raise ValueError("message has no frames")
        for f in frames:
            _check_frame(f)
        mode = d.get("mode", "left")
        mode = Mode(mode) if isinstance(mode, int) else Mode[mode.upper()]
        speed = int(d.get("speed", 4))
        if not 1 <= speed <= 8:
            raise ValueError("speed must be 1..8")
        return cls(frames, mode, speed, bool(d.get("blink", False)), bool(d.get("marquee", False)))

    @classmethod
    def from_message(cls, msg: Message, frame_width: int = 48, frame_offset: int = ANIM_OFFSET) -> "DesignMessage":
        """Convert a protocol Message (e.g. generated by the CLI) into editable frames."""
        img = msg.bitmap.convert("1")
        if msg.mode == Mode.ANIMATION:
            frames = [image_to_rows(img.crop((x + frame_offset, 0, x + frame_offset + 44, HEIGHT)))
                      for x in range(0, img.width, frame_width)]
        else:
            frames = [image_to_rows(img)]
        return cls(frames, msg.mode, msg.speed, msg.blink, msg.marquee)


@dataclass
class Design:
    """A named set of up to 8 messages plus brightness."""
    name: str
    messages: list[DesignMessage] = field(default_factory=list)
    brightness: int = 100

    def to_messages(self, frame_offset: int = ANIM_OFFSET) -> list[Message]:
        return [m.to_message(frame_offset) for m in self.messages]

    def payload(self, frame_offset: int = ANIM_OFFSET) -> bytes:
        """Full upload payload; raises ValueError if it doesn't fit the badge."""
        return build_payload(self.to_messages(frame_offset), brightness=self.brightness)

    def to_json(self) -> dict:
        return {"version": FORMAT_VERSION, "name": self.name, "brightness": self.brightness,
                "messages": [m.to_json() for m in self.messages]}

    @classmethod
    def from_json(cls, d: dict) -> "Design":
        msgs = [DesignMessage.from_json(m) for m in d.get("messages", [])]
        if not 1 <= len(msgs) <= MAX_MESSAGES:
            raise ValueError(f"design needs 1..{MAX_MESSAGES} messages")
        brightness = int(d.get("brightness", 100))
        if brightness not in (25, 50, 75, 100):
            raise ValueError("brightness must be 25, 50, 75 or 100")
        return cls(validate_name(d.get("name", "untitled")), msgs, brightness)


def combine(designs: list[Design], name: str = "combined", brightness: int | None = None) -> Design:
    """Concatenate the messages of several designs into one upload (the badge cycles through them).

    Brightness is per upload on the badge, so it comes from ``brightness`` or the first design.

    Raises:
        ValueError: if the result has more than 8 messages or exceeds the 8 KB payload.
    """
    if not designs:
        raise ValueError("no designs to combine")
    msgs = [m for d in designs for m in d.messages]
    if len(msgs) > MAX_MESSAGES:
        raise ValueError(f"{len(msgs)} messages in total; the badge holds at most {MAX_MESSAGES}")
    out = Design(name, msgs, designs[0].brightness if brightness is None else brightness)
    try:
        out.payload()
    except ValueError as e:
        sizes = ", ".join(f"{d.name} {len(d.payload())} B" for d in designs)
        raise ValueError(f"{e} ({sizes})") from e
    return out


def validate_name(name: str) -> str:
    """Design names double as file names, so keep them simple and path-safe."""
    name = name.strip()
    if not _NAME_RE.match(name):
        raise ValueError("design name: 1-64 chars, letters/digits/space/_ . - , "
                         "not starting with a symbol")
    return name


class DesignStore:
    """A folder of ``<name>.json`` design files."""

    def __init__(self, folder: str | Path = "designs") -> None:
        self.folder = Path(folder)

    def path(self, name: str) -> Path:
        return self.folder / f"{validate_name(name)}.json"

    def names(self) -> list[str]:
        if not self.folder.is_dir():
            return []
        return sorted(p.stem for p in self.folder.glob("*.json"))

    def load(self, name: str) -> Design:
        p = self.path(name)
        if not p.exists():
            raise FileNotFoundError(f"no design named {name!r} in {self.folder}/")
        return Design.from_json(json.loads(p.read_text()))

    def save(self, design: Design) -> Path:
        design.payload()  # refuse to save something that can't be uploaded
        self.folder.mkdir(parents=True, exist_ok=True)
        p = self.path(design.name)
        p.write_text(json.dumps(design.to_json(), indent=1) + "\n")
        return p

    def delete(self, name: str) -> None:
        self.path(name).unlink(missing_ok=True)
