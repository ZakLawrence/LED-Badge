Glyph = list[str]


def _parse(src: dict[str, str], rows: int) -> dict[str, Glyph]:
    """Turn the compact space-separated glyph strings into padded row lists."""
    out: dict[str, Glyph] = {}
    for ch, spec in src.items():
        g = spec.split(" ")
        width = len(g[0])
        if any(len(r) != width for r in g) or len(g) > rows:
            raise ValueError(f"malformed glyph {ch!r}")
        out[ch] = g + ["." * width] * (rows - len(g))
    return out


FONTS: dict[str, tuple[dict[str, Glyph], int]] = {
    # name -> (glyphs, top row offset on the 11-row display)
    "small": (_parse(_SMALL_SRC, 9), 1),
    "big": (_parse(_BIG_SRC, 9), 1),
}


def text_width(text: str, font: str = "small", spacing: int = 1) -> int:
    """Width in pixels of ``text`` rendered with :func:`render_text`."""
    glyphs, _ = FONTS[font]
    widths = [len(glyphs.get(ch, glyphs.get("?", glyphs[" "]))[0]) for ch in text]
    return sum(widths) + spacing * max(len(widths) - 1, 0)


def render_text(text: str, font: str = "small", spacing: int = 1,
                min_width: int = 0, align: str = "center") -> Image.Image:
    """Render ``text`` into a 1-bit image of height 11.

    Args:
        text: String to render. Unknown characters fall back to ``?``.
        font: ``"small"`` or ``"big"``.
        spacing: Blank columns between glyphs.
        min_width: Pad the result to at least this width (e.g. 44 for a
            static message that should fill the display).
        align: ``"left"``, ``"center"`` or ``"right"`` when padding.

    Returns:
        A mode ``"1"`` PIL image, 11 pixels high.
    """
    glyphs, top = FONTS[font]
    fallback = glyphs.get("?", glyphs[" "])
    width = text_width(text, font, spacing)
    full = max(width, min_width)
    x = {"left": 0, "center": (full - width) // 2, "right": full - width}[align]
    img = Image.new("1", (max(full, 1), HEIGHT), 0)
    px = img.load()
    for ch in text:
        g = glyphs.get(ch, fallback)
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == "#":
                    px[x + c, top + r] = 1
        x += len(g[0]) + spacing
    return img
